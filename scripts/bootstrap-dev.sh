#!/usr/bin/env bash
# Prepare a Choreo development machine. Idempotent: safe to re-run at any time.
#
# Scope (lot L0.1 of docs/PLAN.md):
#   - install the Go toolchain locally, without sudo
#   - point ANDROID_HOME at the SDK that is already present
#   - make sure the Linux Flutter SDK wins over any Windows one leaking in
#     through WSL PATH interop
#
# Everything lands in $HOME. No sudo, no package manager, no system file
# touched: see principle 1 of the operating rules (nothing by hand).

set -euo pipefail

GO_VERSION="1.27.1"
GITLEAKS_VERSION="8.30.1"
GO_ROOT="${HOME}/.local/go"
LOCAL_BIN="${HOME}/.local/bin"
FLUTTER_ROOT="${HOME}/flutter"
ANDROID_SDK="${HOME}/Android/Sdk"
ENV_FILE="${HOME}/.config/choreo/dev-env.sh"
ENV_GUARD="# choreo dev env"

say() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }
ok()  { printf '    \033[32mok\033[0m  %s\n' "$1"; }
warn() { printf '    \033[33m!!\033[0m  %s\n' "$1"; }

# --------------------------------------------------------------------------
say "Go ${GO_VERSION}"

if [ -x "${GO_ROOT}/bin/go" ] && "${GO_ROOT}/bin/go" version | grep -q "go${GO_VERSION}"; then
  ok "already installed in ${GO_ROOT}"
else
  tarball="go${GO_VERSION}.linux-amd64.tar.gz"
  tmp="$(mktemp -d)"
  trap 'rm -rf "${tmp}"' EXIT

  echo "    downloading ${tarball}"
  curl -fsSL -o "${tmp}/${tarball}" "https://go.dev/dl/${tarball}"

  # A partial download must never masquerade as a working toolchain.
  echo "    checking the archive"
  tar -tzf "${tmp}/${tarball}" >/dev/null

  rm -rf "${GO_ROOT}"
  mkdir -p "$(dirname "${GO_ROOT}")"
  tar -C "$(dirname "${GO_ROOT}")" -xzf "${tmp}/${tarball}"
  ok "installed in ${GO_ROOT}"
fi

# --------------------------------------------------------------------------
say "Android SDK"

if [ -d "${ANDROID_SDK}/platform-tools" ]; then
  ok "found in ${ANDROID_SDK}"
else
  warn "no SDK in ${ANDROID_SDK} — building an APK will fail"
fi

# --------------------------------------------------------------------------
say "Flutter"

if [ -x "${FLUTTER_ROOT}/bin/flutter" ]; then
  ok "found in ${FLUTTER_ROOT}"
else
  warn "no Linux SDK in ${FLUTTER_ROOT}"
  warn "install it there — never use a Windows SDK through /mnt/c (decision D-011)"
fi

# --------------------------------------------------------------------------
say "gitleaks ${GITLEAKS_VERSION}"

mkdir -p "${LOCAL_BIN}"
if [ -x "${LOCAL_BIN}/gitleaks" ] && "${LOCAL_BIN}/gitleaks" version | grep -q "${GITLEAKS_VERSION}"; then
  ok "already installed in ${LOCAL_BIN}"
else
  tmp="$(mktemp -d)"
  trap 'rm -rf "${tmp}"' EXIT
  echo "    downloading"
  curl -fsSL -o "${tmp}/gitleaks.tar.gz" \
    "https://github.com/gitleaks/gitleaks/releases/download/v${GITLEAKS_VERSION}/gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz"
  tar -C "${LOCAL_BIN}" -xzf "${tmp}/gitleaks.tar.gz" gitleaks
  chmod +x "${LOCAL_BIN}/gitleaks"
  ok "installed in ${LOCAL_BIN}"
fi

# The hook only guards this clone: core.hooksPath is local configuration, it
# does not travel with a push. Anyone cloning has to run this script too.
if git rev-parse --git-dir >/dev/null 2>&1; then
  git config core.hooksPath .githooks
  chmod +x .githooks/* 2>/dev/null || true
  ok "core.hooksPath pointed at .githooks"
else
  warn "not inside a git repository — pre-commit hook not wired"
fi

# --------------------------------------------------------------------------
say "Shell environment"

mkdir -p "$(dirname "${ENV_FILE}")"
cat > "${ENV_FILE}" <<EOF
${ENV_GUARD} — generated by scripts/bootstrap-dev.sh, do not edit by hand
export GOROOT="${GO_ROOT}"
export GOPATH="\${HOME}/go"
export ANDROID_HOME="${ANDROID_SDK}"
export ANDROID_SDK_ROOT="\${ANDROID_HOME}"

# Prepended, not appended: WSL inherits the Windows PATH, which may carry a
# Windows Flutter SDK that cannot run under Linux. Ours has to come first.
export PATH="${LOCAL_BIN}:\${GOROOT}/bin:\${GOPATH}/bin:${FLUTTER_ROOT}/bin:\${ANDROID_HOME}/platform-tools:\${ANDROID_HOME}/cmdline-tools/latest/bin:\${PATH}"
EOF
ok "written to ${ENV_FILE}"

for rc in "${HOME}/.zshrc" "${HOME}/.bashrc"; do
  [ -f "${rc}" ] || continue
  if grep -qF "${ENV_GUARD}" "${rc}"; then
    ok "$(basename "${rc}") already sources it"
  else
    {
      echo ""
      echo "${ENV_GUARD}"
      echo "[ -f \"\${HOME}/.config/choreo/dev-env.sh\" ] && . \"\${HOME}/.config/choreo/dev-env.sh\""
    } >> "${rc}"
    ok "$(basename "${rc}") now sources it"
  fi
done

# --------------------------------------------------------------------------
say "Check"

# shellcheck disable=SC1090
. "${ENV_FILE}"

printf '    go       : %s\n' "$(go version 2>&1 | head -1)"
printf '    flutter  : %s\n' "$(flutter --version 2>&1 | head -1 || echo 'unavailable')"
printf '    dart     : %s\n' "$(dart --version 2>&1 | head -1 || echo 'unavailable')"
printf '    adb      : %s\n' "$(adb version 2>&1 | head -1 || echo 'unavailable')"
printf '    docker   : %s\n' "$(docker --version 2>&1 | head -1 || echo 'unavailable')"
printf '    java     : %s\n' "$(java -version 2>&1 | head -1 || echo 'unavailable')"
printf '    gitleaks : %s\n' "$(gitleaks version 2>&1 | head -1 || echo 'unavailable')"

say "Done — open a new shell, or run: . ${ENV_FILE}"
